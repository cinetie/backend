import { Router } from 'express';
import usersRoute from './usersRoute';
import profileRoute from './profileRoute';
import planRoute from './planRoute';
import access from '../middlewares/access';
import transRoute from './transRoute';
import videoRoute from './videoRoutes';
import videoSessionRoute from './videoSessionRoutes';
import cpRoutes from './cpRoutes';
import cpTransRoutes from './cpTransRoutes';
import tempVideoRouters from './tempVideoRoute';
import trailerRoutes from './trailerRoutes';
import admin from './adminRoutes';
import series from './seriesRoutes';
import tempSeries from './tempSerieRoutes';

const router = Router();

router.use('/cp', cpRoutes);
router.use('/auth', usersRoute);
router.use('/plan', planRoute);
router.use('/trans', transRoute);
router.use('/video', videoRoute);
router.use('/cp/trans', cpTransRoutes);
router.use('/sessions/video', access.isProducer, videoSessionRoute);
router.use('/profile', access.isNormalUser, profileRoute);
router.use('/temp', tempVideoRouters);
router.use('/trailer', trailerRoutes);
router.use('/admin', admin);
router.use('/series', series);
router.use('/temp/series', tempSeries);
export default router;
